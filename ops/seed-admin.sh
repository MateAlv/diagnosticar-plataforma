#!/usr/bin/env bash
# Promote an existing account to admin, or create the first one.
#
# There is no bootstrap path in the application itself, deliberately: an
# endpoint that mints the first admin is a permanent hole once the first admin
# exists. So the first one is seeded here, from a shell on the node, by someone
# who already has database access. Every admin after that is invited from the
# backoffice.
#
#   ops/seed-admin.sh you@example.org              # promote an existing account
#   ops/seed-admin.sh you@example.org --create     # create it, print a password
#   COMPOSE_PROJECT=diagnosticar-staging ops/seed-admin.sh you@example.org
#
# Run it on the host running the stack; it talks to the db container directly.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

EMAIL="${1:-}"
MODE="${2:-}"
[ -n "$EMAIL" ] || { echo "usage: ops/seed-admin.sh <email> [--create]" >&2; exit 1; }

PROJECT="${COMPOSE_PROJECT:-}"
ENV_FILE="${ENV_FILE:-$REPO_ROOT/.env}"
COMPOSE=(docker compose)
[ -n "$PROJECT" ] && COMPOSE+=(-p "$PROJECT")
[ -f "$ENV_FILE" ] && COMPOSE+=(--env-file "$ENV_FILE")

# Read the two values needed rather than sourcing the file: STAGING_BASIC_AUTH
# holds an htpasswd hash whose "$$" the shell would expand to a process id.
# Nothing here uses it, but sourcing corrupts it for anything that reads the
# environment afterwards.
read_env() {
    [ -f "$ENV_FILE" ] || return 0
    sed -n "s/^$1=//p" "$ENV_FILE" | head -1
}

DB_USER="$(read_env POSTGRES_USER)"; DB_USER="${DB_USER:-diagnosticar}"
DB_NAME="$(read_env POSTGRES_DB)"; DB_NAME="${DB_NAME:-diagnosticar}"

psql_do() {
  "${COMPOSE[@]}" exec -T db psql -U "$DB_USER" -d "$DB_NAME" -qtAX -c "$1"
}

escape() { printf '%s' "$1" | sed "s/'/''/g"; }
EMAIL_SQL="$(escape "$EMAIL")"

exists="$(psql_do "SELECT 1 FROM users WHERE email = '$EMAIL_SQL' LIMIT 1;" || true)"

if [ "$exists" != "1" ]; then
  if [ "$MODE" != "--create" ]; then
    echo "No account for $EMAIL." >&2
    echo "Sign up through the app first, or re-run with --create." >&2
    exit 1
  fi

  # bcrypt, cost 12 — the same hash the application produces, generated by the
  # application's own bcryptjs so this script cannot drift from it.
  # Read a bounded slice rather than piping /dev/urandom into head: tr keeps
  # reading after head exits, dies on SIGPIPE, and under `set -e` takes the
  # whole script with it — silently, right after the password is generated and
  # before anything is printed.
  password="$(LC_ALL=C head -c 256 /dev/urandom | LC_ALL=C tr -dc 'A-HJ-NP-Za-km-z2-9' | cut -c1-20)"
  hash="$("${COMPOSE[@]}" exec -T backend node -e \
    "import('bcryptjs').then(b => b.default.hash(process.argv[1], 12)).then(h => process.stdout.write(h))" \
    "$password")"

  psql_do "INSERT INTO users (email, password_hash, full_name, role, status, verified, must_change_password)
           VALUES ('$EMAIL_SQL', '$(escape "$hash")', NULL, 'admin', 'active', TRUE, TRUE);" >/dev/null

  echo "Created $EMAIL as admin."
  echo
  echo "  Temporary password: $password"
  echo
  echo "It is shown once and must be changed at first sign-in."
  exit 0
fi

psql_do "UPDATE users
            SET role = 'admin',
                status = 'active',
                verified = TRUE,
                token_version = token_version + 1
          WHERE email = '$EMAIL_SQL';" >/dev/null

echo "Promoted $EMAIL to admin."
echo "Existing sessions for that account were invalidated; sign in again."
